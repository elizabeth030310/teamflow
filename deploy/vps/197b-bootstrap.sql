\set ON_ERROR_STOP on

BEGIN;
SET LOCAL search_path = public, pg_catalog;
SELECT pg_advisory_xact_lock(197, 2);

DO $bootstrap$
BEGIN
    IF current_database() <> 'teamflow_staging'
       OR session_user <> 'teamflow_staging_owner'
       OR current_user <> session_user
       OR current_setting('server_version_num')::integer NOT BETWEEN 160000 AND 169999 THEN
        RAISE EXCEPTION 'Use the dedicated PostgreSQL 16 teamflow_staging database as teamflow_staging_owner';
    END IF;

    IF EXISTS (SELECT FROM pg_database WHERE datname NOT IN ('teamflow_staging', 'postgres', 'template0', 'template1'))
       OR EXISTS (SELECT FROM pg_namespace WHERE nspname <> 'public'
                  AND nspname <> 'information_schema' AND nspname !~ '^pg_')
       OR EXISTS (SELECT FROM pg_depend WHERE refclassid = 'pg_namespace'::regclass
                  AND refobjid = 'public'::regnamespace) THEN
        RAISE EXCEPTION 'Bootstrap requires a dedicated cluster and an empty staging database';
    END IF;
END
$bootstrap$;

CREATE ROLE teamflow_staging_app LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

REVOKE CONNECT ON DATABASE postgres, template1 FROM PUBLIC;
REVOKE ALL ON DATABASE teamflow_staging FROM PUBLIC;
REVOKE ALL ON SCHEMA public FROM PUBLIC;

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    account_status varchar(20) NOT NULL DEFAULT 'ACTIVE'
        CONSTRAINT users_account_status_domain CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN')),
    access_revision bigint NOT NULL DEFAULT 0
        CONSTRAINT users_access_revision_nonnegative CHECK (access_revision >= 0),
    created_at timestamp(6) without time zone NOT NULL
);

CREATE UNIQUE INDEX users_single_admin_role_idx ON users (role) WHERE role = 'ADMIN';

CREATE TABLE projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255),
    description varchar(255),
    owner_id bigint REFERENCES users (id)
);

CREATE TABLE project_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users (id),
    status varchar(255) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT uk_project_members_project_user UNIQUE (project_id, user_id)
);

CREATE TABLE tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint REFERENCES projects (id) ON DELETE CASCADE,
    title varchar(255),
    description varchar(255),
    status varchar(255),
    priority varchar(255),
    due_date date,
    assignee_id bigint REFERENCES users (id)
);

CREATE INDEX idx_tasks_project_id ON tasks (project_id);

CREATE TABLE task_activities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    task_id bigint NOT NULL,
    task_title varchar(255) NOT NULL,
    type varchar(255) NOT NULL CHECK (type IN (
        'TASK_CREATED', 'TASK_STATUS_CHANGED', 'TASK_ASSIGNEE_CHANGED',
        'COMMENT_CREATED', 'COMMENT_DELETED', 'TASK_DELETED'
    )),
    previous_status varchar(20),
    new_status varchar(20),
    previous_assignee_id bigint,
    new_assignee_id bigint,
    actor_id bigint NOT NULL,
    actor_name varchar(50) NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE INDEX idx_task_activities_project_created ON task_activities (project_id, created_at, id);

CREATE TABLE task_comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    author_id bigint NOT NULL REFERENCES users (id),
    parent_comment_id bigint,
    deleted boolean NOT NULL DEFAULT false,
    content varchar(1000) NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE INDEX idx_task_comments_task_created ON task_comments (task_id, created_at, id);
CREATE INDEX idx_task_comments_parent ON task_comments (parent_comment_id);
CREATE UNIQUE INDEX idx_task_comments_task_id_id ON task_comments (task_id, id);

ALTER TABLE task_comments
    ADD CONSTRAINT fk_task_comments_same_task_parent
        FOREIGN KEY (task_id, parent_comment_id) REFERENCES task_comments (task_id, id);

CREATE TABLE task_checklist_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    title varchar(200) NOT NULL,
    completed boolean NOT NULL DEFAULT false
);

CREATE INDEX idx_task_checklist_items_task_id ON task_checklist_items (task_id, id);

CREATE TABLE task_attachments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    uploader_id bigint NOT NULL REFERENCES users (id),
    display_name varchar(255) NOT NULL,
    storage_key uuid NOT NULL,
    content_type varchar(100) NOT NULL,
    size_bytes bigint NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_task_attachments_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_task_attachments_size CHECK (size_bytes > 0)
);

CREATE INDEX idx_task_attachments_task_created ON task_attachments (task_id, created_at DESC, id DESC);

CREATE TABLE attachment_file_deletions (
    storage_key uuid PRIMARY KEY,
    next_attempt_at timestamptz NOT NULL
);

CREATE INDEX idx_attachment_file_deletions_next_attempt ON attachment_file_deletions (next_attempt_at);

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    task_id bigint NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    kind varchar(20) NOT NULL CHECK (kind IN ('ASSIGNMENT', 'COMMENT', 'COMMENT_REPLY', 'DUE_SOON', 'OVERDUE')),
    due_date date,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at timestamptz,
    actor_name text,
    parent_comment_id bigint,
    reply_comment_id bigint,
    UNIQUE (recipient_id, task_id, kind, due_date)
);

CREATE INDEX idx_notifications_recipient_id ON notifications (recipient_id, id DESC);
CREATE INDEX idx_notifications_task ON notifications (task_id);

CREATE TABLE signup_verifications (
    email_key varchar(64) PRIMARY KEY,
    salt uuid NOT NULL,
    code_mac bytea,
    expires_at timestamptz NOT NULL,
    resend_at timestamptz NOT NULL,
    failed_attempts integer NOT NULL CHECK (failed_attempts BETWEEN 0 AND 5)
);

CREATE INDEX signup_verifications_expiry_idx ON signup_verifications (expires_at);

CREATE TABLE signup_send_limits (
    scope_key varchar(72) PRIMARY KEY,
    window_ends_at timestamptz NOT NULL,
    sends integer NOT NULL CHECK (sends > 0)
);

CREATE INDEX signup_send_limits_expiry_idx ON signup_send_limits (window_ends_at);

CREATE TABLE admin_member_audit (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_id bigint NOT NULL REFERENCES users (id),
    target_id bigint NOT NULL REFERENCES users (id),
    from_status varchar(20) NOT NULL,
    to_status varchar(20) NOT NULL,
    target_revision bigint NOT NULL,
    reason varchar(300) NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (actor_id <> target_id),
    UNIQUE (target_id, target_revision)
);

CREATE TABLE project_pages (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    parent_page_id bigint,
    title varchar(200) NOT NULL CHECK (btrim(title) <> ''),
    content text NOT NULL DEFAULT '',
    content_format text NOT NULL DEFAULT 'plain',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (project_id, id),
    CHECK (parent_page_id <> id),
    FOREIGN KEY (project_id, parent_page_id) REFERENCES project_pages (project_id, id),
    CONSTRAINT project_pages_content_check CHECK (
        (content_format = 'plain' AND char_length(content) <= 100000)
        OR (content_format = 'rich-v1' AND char_length(content) <= 6000000)
    )
);

CREATE INDEX project_pages_parent_idx ON project_pages (project_id, parent_page_id, id);

GRANT CONNECT ON DATABASE teamflow_staging TO teamflow_staging_app;
GRANT USAGE ON SCHEMA public TO teamflow_staging_app;

GRANT SELECT ON users TO teamflow_staging_app;
GRANT INSERT (name, email, password, created_at), UPDATE (password, account_status, access_revision)
    ON users TO teamflow_staging_app;

GRANT SELECT, INSERT, UPDATE, DELETE ON projects, tasks, task_comments, task_checklist_items,
    attachment_file_deletions, signup_verifications TO teamflow_staging_app;
GRANT SELECT, INSERT, UPDATE ON project_members TO teamflow_staging_app;
GRANT SELECT, INSERT, DELETE ON task_attachments TO teamflow_staging_app;
GRANT SELECT, INSERT ON task_activities, admin_member_audit TO teamflow_staging_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON signup_send_limits TO teamflow_staging_app;
GRANT SELECT, INSERT, UPDATE (read_at) ON notifications TO teamflow_staging_app;
GRANT SELECT, INSERT, UPDATE (parent_page_id, title, content, content_format, updated_at), DELETE
    ON project_pages TO teamflow_staging_app;

COMMIT;
