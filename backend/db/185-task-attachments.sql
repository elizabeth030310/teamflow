CREATE TABLE task_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    uploader_id BIGINT NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    storage_key UUID NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_task_attachments_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_task_attachments_uploader FOREIGN KEY (uploader_id) REFERENCES users (id),
    CONSTRAINT uk_task_attachments_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_task_attachments_size CHECK (size_bytes > 0)
);

CREATE INDEX idx_task_attachments_task_created ON task_attachments (task_id, created_at DESC, id DESC);
