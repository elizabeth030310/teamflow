BEGIN;

ALTER TABLE tasks ADD COLUMN IF NOT EXISTS due_date DATE;

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    task_id BIGINT NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('ASSIGNMENT', 'COMMENT', 'DUE_SOON', 'OVERDUE')),
    due_date DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITH TIME ZONE,
    UNIQUE (recipient_id, task_id, kind, due_date)
);

CREATE INDEX IF NOT EXISTS idx_notifications_recipient_id ON notifications (recipient_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_task ON notifications (task_id);

COMMIT;
